import {readFile,writeFile} from "node:fs/promises";
import {fileURLToPath,pathToFileURL} from "node:url";
import path from "node:path";
const root=fileURLToPath(new URL("../",import.meta.url));
export function renderFlowIndex(registry){
  const groups=new Map();
  for(const flow of registry.flows){
    if(!groups.has(flow.guide))groups.set(flow.guide,[]);
    groups.get(flow.guide).push(flow);
  }
  const sections=[`<!-- Generated by scripts/update-guide-index.mjs. -->`,`${registry.flows.length} documented flows. Each ID links directly to its instructions.`];
  for(const [guide,flows]of groups){
    const label=registry.chapters.find(c=>c.path===guide)?.title??guide;
    const rows=flows.map(f=>`| [${f.id}](${guide.replace(/^docs\//,"")}#${f.anchor}) | ${f.title.replaceAll("|","\\|")} |`);
    sections.push(`### ${label}\n\n| Flow | What you can do |\n| --- | --- |\n${rows.join("\n")}`);
  }
  return sections.join("\n\n");
}
export function updatedGuide(text,registry){
  const marker=/<!-- flow-index:start -->[\s\S]*?<!-- flow-index:end -->/;
  if(!marker.test(text))throw new Error("The guide is missing its generated index markers.");
  return text.replace(marker,`<!-- flow-index:start -->\n${renderFlowIndex(registry)}\n<!-- flow-index:end -->`)
    .replace(/^\*\*Product version:\*\* .+$/m,`**Product version:** ${registry.productVersion}`)
    .replace(/^\*\*Last reviewed:\*\* .+$/m,`**Last reviewed:** ${registry.lastReviewed}`);
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
  const registry=JSON.parse(await readFile(path.join(root,"docs/flows.json"),"utf8"));
  const guide=path.join(root,"docs/USER-GUIDE.md");
  await writeFile(guide,updatedGuide(await readFile(guide,"utf8"),registry));
  console.log(`Updated handbook index: ${registry.flows.length} flows for ${registry.productVersion}.`);
}
